// Shape probe for one AutoCount Cloud account book.
//
//   node cloud-probe.mjs [bookId]
//
// The vendor documentation describes the API; it does not describe THIS
// tenant's books. This script asks the live tenant three questions that decide
// what the dashboard can honestly contain, and refuses to guess at any of them:
//
//   Q1  Is the general ledger reconstructible?
//       AutoCount posts every document type to the GL. The API has no /ledger
//       endpoint, so the ledger has to be rebuilt from document details. The
//       open question is whether /journalentry returns ONLY hand-written
//       journals, or also the postings generated by invoices and payments.
//       Get this wrong in the first direction and revenue vanishes; wrong in
//       the second and it is counted twice. Both draw a perfectly good chart.
//
//   Q2  Are accounts classified?  accType drives revenue vs cost;
//       specialAccType drives which accounts are bank and cash.
//
//   Q3  Can ageing be computed?  Needs outstandingAmount, a cancelled flag,
//       and dueDate - ageing from invoice date instead of due date is one of
//       the traps in references/accounting-pitfalls.md.
//
// Output is shapes and aggregates. Customer and supplier names are reduced to
// a character count; no counterparty is named and no individual document
// amount is printed.
import { request, pageAll, assertFields, credentialsPresent, BOOKS, BASE_URL, redact } from "./cloud-api.js";

const book = process.argv[2] || BOOKS[0];
if (!credentialsPresent() || !book) {
  console.error(
    "Need credentials and a book id.\n" +
    "Put ACCT_CLOUD_KEY_ID / ACCT_CLOUD_API_KEY / ACCT_CLOUD_BOOKS in " +
    "assets/mcp-server/.env, or pass a book id as an argument."
  );
  process.exit(2);
}

const H = (s) => console.log("\n" + s + "\n" + "-".repeat(s.length));
const money = (n) => (Math.round(n * 100) / 100).toLocaleString();

// Describes a record's shape without disclosing its contents.
function shape(obj, depth = 0) {
  if (obj === null || obj === undefined) return "null";
  if (Array.isArray(obj)) return "array<" + (obj.length ? shape(obj[0], depth + 1) : "?") + ">[" + obj.length + "]";
  if (typeof obj !== "object") return typeof obj;
  if (depth > 1) return "object";
  return "{ " + Object.keys(obj).join(", ") + " }";
}
function fieldsWithValues(rows, keys) {
  // Which of these keys are actually populated, rather than merely present?
  const out = {};
  for (const k of keys) {
    const filled = rows.filter((r) => r?.[k] !== null && r?.[k] !== undefined && r?.[k] !== "").length;
    out[k] = filled + "/" + rows.length;
  }
  return out;
}
const distinct = (rows, k) => {
  const m = new Map();
  for (const r of rows) { const v = r?.[k] ?? "(null)"; m.set(v, (m.get(v) || 0) + 1); }
  return [...m.entries()].sort((a, b) => b[1] - a[1]);
};

console.log("AutoCount Cloud probe");
console.log("base: " + BASE_URL);
console.log("book: " + book);

// ------------------------------------------------------------------ reachable
H("connectivity");
let profile;
try {
  profile = await request("GET", "/{book}/companyprofile", { book });
  console.log("companyprofile OK   fields: " + shape(profile));
} catch (e) {
  console.error("FAILED - " + redact(e.message).slice(0, 300));
  console.error("\nIf this is 401/403: the key may be inactive, or 'Get Company Profile'");
  console.error("may not be enabled in its permission list.");
  process.exit(1);
}

// --------------------------------------------------------------------- Q2
H("Q2  chart of accounts - classification");
let accounts = [];
try {
  // The listing returns a minimal column set unless `field` asks for more, and
  // silently drops names it does not recognise. Without this the classification
  // columns come back absent and look like unclassified books.
  const ACCT_FIELDS = ["AccNo", "Description", "AccType", "SpecialAccType", "ParentAccNo"];
  const r = await pageAll("POST", "/{book}/account/listing",
    { book, query: { field: ACCT_FIELDS }, body: {}, max: 50 });
  accounts = r.rows;
  assertFields(accounts, ACCT_FIELDS, "account/listing");
  console.log("accounts: " + accounts.length + (r.total !== null ? " of " + r.total : ""));
  if (accounts.length) {
    console.log("record shape: " + shape(accounts[0]));
    console.log("\nAccType:");
    for (const [v, n] of distinct(accounts, "AccType")) console.log("   " + String(v).padEnd(10) + n);
    console.log("\nSpecialAccType:");
    for (const [v, n] of distinct(accounts, "SpecialAccType")) console.log("   " + String(v).padEnd(16) + n);
    console.log("\nQ2 VERDICT: " + (distinct(accounts, "AccType").length > 1
      ? "classified - revenue/cost split is possible"
      : "NOT classified - accType is uniform, revenue vs cost cannot be derived"));
    const banks = accounts.filter((a) => /BANK|CASH|SBK|SCH/i.test(String(a.SpecialAccType || "")));
    console.log("            bank/cash accounts identifiable: " +
      (banks.length ? "yes (" + banks.length + ")" : "NO - cash position will be unavailable"));
  }
} catch (e) {
  console.log("FAILED - " + redact(e.message).split("\n")[0].slice(0, 160));
  console.log("Q2 VERDICT: unknown - endpoint not reachable (permission?)");
}

// ------------------------------------------------------- find a month with data
H("finding a month with activity");
const today = new Date();
let probeMonth = null, invoices = [];
for (let back = 1; back <= 24 && !probeMonth; back++) {
  const start = new Date(Date.UTC(today.getUTCFullYear(), today.getUTCMonth() - back, 1));
  const end   = new Date(Date.UTC(today.getUTCFullYear(), today.getUTCMonth() - back + 1, 0));
  const iso = (d) => d.toISOString().slice(0, 10);
  try {
    const { rows } = await pageAll("GET", "/{book}/invoice/listing",
      { book, query: { startDate: iso(start), endDate: iso(end) }, max: 5 });
    if (rows.length) { probeMonth = { start: iso(start), end: iso(end) }; invoices = rows; }
  } catch (e) {
    console.log("  invoice/listing failed: " + redact(e.message).split("\n")[0].slice(0, 120));
    break;
  }
}
if (!probeMonth) console.log("no invoices found in the last 24 months - is this book dormant?");
else console.log("using " + probeMonth.start + " .. " + probeMonth.end + "  (" + invoices.length + " invoices)");

// --------------------------------------------------------------------- Q3
H("Q3  AR ageing - outstanding, cancelled, due date");
if (invoices.length) {
  const first = invoices[0];
  const master = first.master ?? first;
  console.log("listing record shape: " + shape(first));
  console.log("master fields present: " + Object.keys(master).length);
  const need = ["docNo", "docDate", "dueDate", "debtorCode", "debtorName",
                "cancelled", "outstandingAmount", "localNetTotal", "creditTerm"];
  const masters = invoices.map((i) => i.master ?? i);
  const filled = fieldsWithValues(masters, need);
  for (const k of need) {
    const present = k in master;
    console.log("   " + k.padEnd(20) + (present ? "present  " + filled[k] : "ABSENT"));
  }
  const cancelledCount = masters.filter((m) => m.cancelled === true).length;
  console.log("\ncancelled in sample: " + cancelledCount + "/" + masters.length);
  const haveDue = "dueDate" in master && masters.some((m) => m.dueDate);
  const haveOut = "outstandingAmount" in master;
  console.log("Q3 VERDICT: " + (haveOut && haveDue
    ? "ageing by DUE DATE is possible - the correct basis"
    : haveOut ? "outstanding available but NO due date - ageing would have to use invoice date (a known trap)"
              : "outstandingAmount ABSENT - ageing must be derived from knockoffentry, or dropped"));
} else console.log("skipped - no invoices to inspect");

// --------------------------------------------------------------------- Q1
H("Q1  is the general ledger reconstructible?");
if (!probeMonth) console.log("skipped - no month with activity");
else {
  let jes = [];
  try {
    const r = await pageAll("GET", "/{book}/journalentry/listing",
      { book, query: { startDate: probeMonth.start, endDate: probeMonth.end }, max: 50 });
    jes = r.rows;
    console.log("journal entries in month: " + jes.length + (r.total !== null ? " of " + r.total : ""));
  } catch (e) {
    console.log("journalentry/listing FAILED - " + redact(e.message).split("\n")[0].slice(0, 140));
  }

  if (jes.length) {
    console.log("record shape: " + shape(jes[0]));
    const masters = jes.map((j) => j.master ?? j);
    console.log("\njournalType:");
    for (const [v, n] of distinct(masters, "journalType")) console.log("   " + String(v).padEnd(14) + n);

    // The decisive test. If the journal entry endpoint carried the postings
    // generated by sales invoices, the invoice document numbers would appear
    // among the journal document numbers. If none do, /journalentry is
    // hand-written journals only and the ledger must be assembled from every
    // document type separately.
    const invNos = new Set(invoices.map((i) => (i.master ?? i).docNo).filter(Boolean));
    const jeNos  = new Set(masters.map((m) => m.docNo).filter(Boolean));
    const overlap = [...invNos].filter((n) => jeNos.has(n)).length;
    console.log("\ninvoice doc numbers appearing in journal entries: " + overlap + "/" + invNos.size);

    const details = jes.flatMap((j) => j.details ?? []);
    console.log("detail lines in sample: " + details.length);
    if (details.length) {
      console.log("detail shape: " + shape(details[0]));
      const dr = details.reduce((s, d) => s + (Number(d.localDR) || 0), 0);
      const cr = details.reduce((s, d) => s + (Number(d.localCR) || 0), 0);
      console.log("sum localDR " + money(dr) + " / localCR " + money(cr) +
        (Math.abs(dr - cr) < 0.01 ? "  (balanced)" : "  (UNBALANCED - listing may be truncated)"));
      console.log("distinct accNo in details: " + new Set(details.map((d) => d.accNo)).size);
      const withDept = details.filter((d) => d.deptNo).length;
      console.log("detail lines carrying deptNo: " + withDept + "/" + details.length +
        (withDept ? "" : "   -> profit by department is NOT available from this data"));
    }
    console.log("\nQ1 VERDICT: " + (overlap > 0
      ? "journalentry INCLUDES document postings - use it as the ledger, and do NOT " +
        "also add invoice/payment details or every figure doubles"
      : "journalentry is hand-written journals ONLY - the ledger must be assembled from " +
        "invoice + purchaseinvoice + creditnote + payment + journalentry details"));
  } else if (invoices.length) {
    console.log("\nQ1 VERDICT: no journal entries in a month that has invoices - strongly " +
      "suggests journalentry holds hand-written journals only.");
  }
}

// ---------------------------------------------------------- endpoint inventory
H("endpoint inventory");
const checks = [
  ["GET",  "/{book}/debtor/listing",        {}],
  ["GET",  "/{book}/creditor/listing",      {}],
  ["GET",  "/{book}/department/listing",    {}],
  ["GET",  "/{book}/purchaseinvoice/listing", probeMonth ? { startDate: probeMonth.start, endDate: probeMonth.end } : {}],
  ["GET",  "/{book}/payment/listing",       probeMonth ? { startDate: probeMonth.start, endDate: probeMonth.end } : {}],
  ["GET",  "/{book}/creditnote/listing",    probeMonth ? { startDate: probeMonth.start, endDate: probeMonth.end } : {}],
  ["GET",  "/{book}/knockoffentry/listing", probeMonth ? { startDate: probeMonth.start, endDate: probeMonth.end } : {}],
];
for (const [method, path, query] of checks) {
  try {
    const r = await request(method, path, { book, query: { ...query, page: 1 } });
    const rows = Array.isArray(r) ? r : (r?.data ?? []);
    const total = r?.totalCount;
    console.log("  OK    " + path.replace("/{book}", "").padEnd(34) +
      String(rows.length).padStart(4) + " rows" +
      (typeof total === "number" ? "  of " + total : "") +
      (rows.length ? "   " + shape(rows[0]) : ""));
  } catch (e) {
    console.log("  FAIL  " + path.replace("/{book}", "").padEnd(34) +
      redact(e.message).split("\n")[0].replace(/^GET \S+ -> /, "").slice(0, 70));
  }
}

console.log("\nProbe complete. The three VERDICT lines decide what build-data-cloud.mjs");
console.log("can compute. Anything marked unavailable stays empty in the dashboard");
console.log("rather than being estimated.");
