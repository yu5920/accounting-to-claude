#!/usr/bin/env node
// Read-only MCP server for AutoCount Cloud Accounting.
//
//   ACCT_CLOUD_KEY_ID / ACCT_CLOUD_API_KEY / ACCT_CLOUD_BOOKS
//
// The sibling index.js speaks SQL to a local database. This one speaks HTTP to
// the vendor, and the difference is not cosmetic: index.js exposes one query
// tool and guards the SQL, because with a database the useful surface is
// arbitrary queries. Here the useful surface is a fixed set of documented
// endpoints, so the tools mirror the endpoints and there is no query language
// to guard. Everything goes through cloud-api.js, which refuses any request
// that is not on its read allowlist.
//
// Run `node cloud-selftest.mjs` before pointing this at live books.
import { Server } from "@modelcontextprotocol/sdk/server/index.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { CallToolRequestSchema, ListToolsRequestSchema } from "@modelcontextprotocol/sdk/types.js";
import { request, pageAll, BOOKS, redact, GuardError, ApiError } from "./cloud-api.js";

const MAX_ROWS = Number(process.env.ACCT_MAX_ROWS) || 2000;

const bookArg = {
  book: {
    type: "string",
    description: "Account book id. Optional when only one book is configured.",
  },
};
const dateArgs = {
  startDate: { type: "string", description: "Inclusive start date, YYYY-MM-DD." },
  endDate:   { type: "string", description: "Inclusive end date, YYYY-MM-DD." },
};

// Each tool is one allowlisted read. `paged: true` walks every page.
const TOOLS = [
  {
    name: "list_account_books",
    description: "The account books this server is configured for. Start here.",
    schema: { type: "object", properties: {} },
    run: async () => ({ books: BOOKS }),
  },
  {
    name: "get_company_profile",
    description: "Company name, registration and address for one account book.",
    schema: { type: "object", properties: { ...bookArg } },
    run: (a, book) => request("GET", "/{book}/companyprofile", { book }),
  },
  {
    name: "list_accounts",
    description:
      "Chart of accounts, with accType (Sales, Expenses, Cost of Goods Sold, " +
      "Other Income...) and specialAccType (Bank, Cash, Debtor Control...). " +
      "Read this before computing anything: accType is what separates revenue " +
      "from cost, and specialAccType is what identifies the bank accounts.",
    schema: {
      type: "object",
      properties: {
        ...bookArg,
        leafOnly: { type: "boolean", description: "Postable accounts only, excluding headers." },
        searchText: { type: "string" },
      },
    },
    run: (a, book) => pageAll("POST", "/{book}/account/listing", {
      book, query: { leafOnly: a.leafOnly, searchText: a.searchText }, body: {},
    }),
  },
  {
    name: "list_departments",
    description:
      "Departments. Whether department codes are actually populated on " +
      "transactions decides if profit by department is possible at all - " +
      "check the detail lines, not just this list.",
    schema: { type: "object", properties: { ...bookArg } },
    run: (a, book) => pageAll("GET", "/{book}/department/listing", { book }),
  },
  {
    name: "list_journal_entries",
    description:
      "Journal entries in a date range, each with its detail lines (accNo, " +
      "localDR, localCR, deptNo). Note: in most books this returns " +
      "hand-written journals only, not the postings generated by invoices and " +
      "payments. Confirm with cloud-probe.mjs before treating it as the ledger.",
    schema: { type: "object", properties: { ...bookArg, ...dateArgs }, required: ["startDate", "endDate"] },
    run: (a, book) => pageAll("GET", "/{book}/journalentry/listing", {
      book, query: { startDate: a.startDate, endDate: a.endDate },
    }),
  },
  {
    name: "get_journal_entry",
    description: "One journal entry in full, by document number.",
    schema: { type: "object", properties: { ...bookArg, docNo: { type: "string" } }, required: ["docNo"] },
    run: (a, book) => request("GET", "/{book}/journalentry", { book, query: { docNo: a.docNo } }),
  },
  {
    name: "list_invoices",
    description:
      "Sales invoices in a date range. Master carries dueDate, cancelled and " +
      "outstandingAmount; details carry accNo per line, which is how revenue " +
      "is split by account. Cancelled invoices keep their amounts - filter them.",
    schema: { type: "object", properties: { ...bookArg, ...dateArgs }, required: ["startDate", "endDate"] },
    run: (a, book) => pageAll("GET", "/{book}/invoice/listing", {
      book, query: { startDate: a.startDate, endDate: a.endDate },
    }),
  },
  {
    name: "get_invoice",
    description: "One sales invoice in full, by document number.",
    schema: { type: "object", properties: { ...bookArg, docNo: { type: "string" } }, required: ["docNo"] },
    run: (a, book) => request("GET", "/{book}/invoice", { book, query: { docNo: a.docNo } }),
  },
  {
    name: "list_purchase_invoices",
    description: "Purchase invoices in a date range, with per-line accNo.",
    schema: { type: "object", properties: { ...bookArg, ...dateArgs }, required: ["startDate", "endDate"] },
    run: (a, book) => pageAll("GET", "/{book}/purchaseinvoice/listing", {
      book, query: { startDate: a.startDate, endDate: a.endDate },
    }),
  },
  {
    name: "list_credit_notes",
    description: "Sales credit notes in a date range. These reduce revenue.",
    schema: { type: "object", properties: { ...bookArg, ...dateArgs }, required: ["startDate", "endDate"] },
    run: (a, book) => pageAll("GET", "/{book}/creditnote/listing", {
      book, query: { startDate: a.startDate, endDate: a.endDate },
    }),
  },
  {
    name: "list_payments",
    description:
      "Cash book entries (payments and receipts) in a date range, with detail " +
      "lines. Watch for transfers between the company's own bank accounts - " +
      "counting both sides inflates cash in and cash out simultaneously.",
    schema: { type: "object", properties: { ...bookArg, ...dateArgs }, required: ["startDate", "endDate"] },
    run: (a, book) => pageAll("GET", "/{book}/payment/listing", {
      book, query: { startDate: a.startDate, endDate: a.endDate },
    }),
  },
  {
    name: "list_debtors",
    description: "Customers.",
    schema: { type: "object", properties: { ...bookArg } },
    run: (a, book) => pageAll("GET", "/{book}/debtor/listing", { book }),
  },
  {
    name: "list_creditors",
    description: "Suppliers.",
    schema: { type: "object", properties: { ...bookArg } },
    run: (a, book) => pageAll("GET", "/{book}/creditor/listing", { book }),
  },
  {
    name: "get_outstanding_transactions",
    description:
      "Unsettled transactions for one control account as at a date - the basis " +
      "for AR or AP ageing. Age from due date, not document date.",
    schema: {
      type: "object",
      properties: { ...bookArg, accNo: { type: "string" }, docDate: { type: "string" } },
      required: ["accNo", "docDate"],
    },
    run: (a, book) => request("GET", "/{book}/knockoffentry/outstandingtransactions", {
      book, query: { accNo: a.accNo, docDate: a.docDate },
    }),
  },
];

const server = new Server(
  { name: "autocount-cloud", version: "1.0.0" },
  { capabilities: { tools: {} } }
);

server.setRequestHandler(ListToolsRequestSchema, async () => ({
  tools: TOOLS.map((t) => ({ name: t.name, description: t.description, inputSchema: t.schema })),
}));

server.setRequestHandler(CallToolRequestSchema, async (req) => {
  const tool = TOOLS.find((t) => t.name === req.params.name);
  if (!tool) return err("Unknown tool: " + req.params.name);

  const args = req.params.arguments || {};
  const book = args.book || BOOKS[0];
  if (!book && tool.name !== "list_account_books") {
    return err("No account book. Set ACCT_CLOUD_BOOKS, or pass `book`.");
  }

  try {
    const result = await tool.run(args, book);
    let rows = result, note = "";

    if (result && typeof result === "object" && Array.isArray(result.rows)) {
      rows = result.rows;
      if (rows.length > MAX_ROWS) {
        note = "Showing the first " + MAX_ROWS + " of " + rows.length +
               " rows. Narrow the date range for the rest.\n";
        rows = rows.slice(0, MAX_ROWS);
      }
      // An empty result is a fact about the books, not a failure. Say which.
      if (!rows.length) {
        return ok("No rows. The request succeeded and the book has nothing " +
                  "matching these criteria.");
      }
      note = (result.total !== null && result.total !== undefined
        ? rows.length + " of " + result.total + " rows\n" : rows.length + " rows\n") + note;
    } else if (rows === null) {
      return ok("No record. The request succeeded and returned nothing.");
    }

    return ok(note + JSON.stringify(rows));
  } catch (e) {
    if (e instanceof GuardError) return err("Blocked by the read-only guard: " + e.message);
    if (e instanceof ApiError) {
      return err(redact(e.message) + (e.status === 403
        ? "\n\nA 403 usually means this method is not enabled in the API key's " +
          "permission list. That list is the read-only boundary - widen it only " +
          "to other read methods."
        : ""));
    }
    return err(redact(String(e && e.message || e)));
  }
});

const ok  = (text) => ({ content: [{ type: "text", text }] });
const err = (text) => ({ content: [{ type: "text", text }], isError: true });

await server.connect(new StdioServerTransport());
